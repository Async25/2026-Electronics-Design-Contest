void HAL_TIM_PeriodElapsedCallback(TIM_HandleTypeDef *htim)
{
  if (htim->Instance != TIM2) {return;}

  if (SerialLossFlag == 1)
  {
    serial_loss_count++;
    if (serial_loss_count >= 100)
    {
      Runflag = 0;
    }
  }
  else
  {
    Runflag = 1;
    serial_loss_count = 0;
  }

  tim2_count ++;

  if (tim2_count % 3 == 0)
  {
    tim2_count = 0;

    if (Runflag)
    {
      // --- YAW 轴追踪 (X坐标) ---
      pidYAW.Target = 320.0f;
      pidYAW.Actual = (float)uart_x;

      if (fabsf(pidYAW.Target - pidYAW.Actual) < 8.0f)
      {
        pidYAW.Out = 0;
        pidYAW.Error1 = 0;
        pidYAW.Error2 = 0;
      }
      else
      {
        PID_Update(&pidYAW);
      }

      Stepper_Set_Speed_Profile(&YAW, -pidYAW.Out, accel);
      if (YAW.state == STOP && fabsf(pidYAW.Out) > 0.5f) {
        Stepper_Run_Speed(&YAW);
      } else if (fabsf(pidYAW.Out) < 0.5f) {
        Stepper_Stop(&YAW);
      }

      // --- PITCH 轴追踪 (Y坐标) ---
      pidPITCH.Target = 240.0f;
      pidPITCH.Actual = (float)uart_y;

      if (fabsf(pidPITCH.Target - pidPITCH.Actual) < 8.0f)
      {
        pidPITCH.Out = 0;
        pidPITCH.Error1 = 0;
        pidPITCH.Error2 = 0;
      }
      else
      {
        PID_Update(&pidPITCH);
      }

      Stepper_Set_Speed_Profile(&PITCH, pidPITCH.Out, accel);
      if (PITCH.state == STOP && fabsf(pidPITCH.Out) > 0.5f) 
      {
        Stepper_Run_Speed(&PITCH);
      } 
      else if (fabsf(pidPITCH.Out) < 0.5f) 
      {
        Stepper_Stop(&PITCH);
      }
    }
    else
    {
      Stepper_Stop(&YAW);
      Stepper_Stop(&PITCH);

      pidYAW.Out = 0;
      pidPITCH.Out = 0;

      pidYAW.Error1 = 0;
      pidYAW.Error2 = 0;
      pidPITCH.Error1 = 0;
      pidPITCH.Error2 = 0;
    }
  }
}

